"""N7: write cutout commands for the picked images. Nothing is executed here."""

from __future__ import annotations

import shlex
from dataclasses import dataclass, field
from pathlib import Path

from scene_trials.errors import ConfigError
from scene_trials.imaging import has_alpha
from scene_trials.layout import Layout
from scene_trials.plan import TrialPlan
from scene_trials.select import Finalized

_PS1_HEADER = "# Generated by scene-trials. Review, then run on the machine that has the cutout tool.\n"
_SH_HEADER = "#!/bin/sh\n# Generated by scene-trials. Review, then run on the machine that has the cutout tool.\nset -e\n"


@dataclass
class CutoutResult:
    commands: dict[str, list[str]] = field(default_factory=dict)
    skipped: list[str] = field(default_factory=list)
    files: list[Path] = field(default_factory=list)


def _quote_ps1(value: str) -> str:
    return "'" + value.replace("'", "''") + "'"


def _quote_sh(value: str) -> str:
    return shlex.quote(value)


_QUOTERS = {"ps1": _quote_ps1, "sh": _quote_sh}


def build_cutout_commands(plan: TrialPlan, finalized: list[Finalized]) -> CutoutResult:
    config = plan.project.cutout
    if not config.templates:
        raise ConfigError("cutout_template_missing", "project.yaml cutout.templates has no ps1 or sh entry")
    scenes = plan.scene_by_id()
    result = CutoutResult(commands={flavor: [] for flavor in config.templates})
    for item in finalized:
        if config.skip_if_transparent and item.transparent is not None and has_alpha(item.transparent):
            result.skipped.append(f"{item.scene_id}: already has a transparent image")
            continue
        section = scenes[item.scene_id].section
        values = {
            "input": str(item.path),
            "output_dir": str(item.path.parent),
            "scene_id": item.scene_id,
            "section": section,
            "trial": str(item.trial),
        }
        for flavor, template in config.templates.items():
            quote = _QUOTERS[flavor]
            try:
                line = template.format(**{k: quote(v) for k, v in values.items()})
            except KeyError as exc:
                raise ConfigError(
                    "cutout_template_bad",
                    f"cutout.templates.{flavor} uses unknown placeholder {exc}; allowed: {sorted(values)}",
                ) from exc
            result.commands[flavor].append(line)

    meta = Layout(plan.project).meta()
    meta.mkdir(parents=True, exist_ok=True)
    for flavor, lines in result.commands.items():
        header = _PS1_HEADER if flavor == "ps1" else _SH_HEADER
        path = meta / f"cutout_commands.{flavor}"
        path.write_text(header + "\n".join(lines) + ("\n" if lines else ""), encoding="utf-8", newline="\n")
        result.files.append(path)
    return result

